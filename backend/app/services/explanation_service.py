import httpx
from app.config import settings

def generate_deterministic_explanation(finding: Dict[str, Any]) -> str:
    """
    Produces an evidence-grounded technical explanation using deterministic rules.
    Used when no LLM API key is configured or as fallback.
    """
    title = finding.get("title", "")
    hostname = finding.get("affected_hostname", "")
    category = finding.get("category", "")
    evidence = finding.get("evidence", {})
    impact_score = finding.get("impact_score", 0.0)
    potential_cat = finding.get("potential_impact_category", "Moderate")

    scanner_cap = evidence.get("scanner_ipv6_capability", "CAPABLE")
    conn_res = evidence.get("connection_result", "UNKNOWN")
    aaaa_recs = evidence.get("dns_aaaa_records", [])

    lines = [
        f"### Technical Diagnostic Summary for {hostname}",
        "",
        f"**Finding:** {title}",
        f"**Potential Impact:** {potential_cat} ({impact_score}/100)",
        "",
        "#### Observed Facts:",
        f"- Target Hostname: `{hostname}`",
        f"- DNS AAAA Records Observed: `{', '.join(aaaa_recs) if aaaa_recs else 'None'}`",
        f"- IPv6 TCP Test Outcome: `{conn_res}`",
        f"- Scanner Host IPv6 Route: `{scanner_cap}`",
        f"- Round-Trip Duration: `{evidence.get('duration_ms', 0):.1f} ms`",
        "",
        "#### Diagnostic Analysis:",
    ]

    if "timeout" in title.lower() or conn_res == "TIMEOUT":
        lines.extend([
            f"1. **Asymmetric Reachability**: The host has published an AAAA record in DNS, signaling to clients that it supports IPv6. However, TCP SYN packets to port 443 were not answered within the connection timeout.",
            f"2. **Most Common Root Causes**: Ingress security groups or hardware firewalls blocking TCP port 443 for IPv6 addresses while allowing IPv4; or an IPv6 BGP routing blackhole at the host's ISP/upstream provider.",
            "3. **User Experience Impact**: Dual-stack clients implementing RFC 8305 (Happy Eyeballs v2) may experience a 250-300ms connection delay before falling back to IPv4. Clients on IPv6-only networks without NAT64 will experience a complete connection failure.",
        ])
    elif "No AAAA" in title or not aaaa_recs:
        lines.extend([
            f"1. **Legacy IPv4 Only**: {hostname} does not publish an IPv6 address in authoritative DNS.",
            "2. **Impact on Delivery Chain**: When an IPv6-only client loads the page, this asset cannot be fetched via direct IPv6 routing and must traverse a NAT64 / DNS64 transition gateway, increasing latency and point-of-failure risk.",
            "3. **Resolution**: Point the DNS record to an IPv6-enabled CDN or reverse proxy.",
        ])
    elif "TLS" in title:
        lines.extend([
            f"1. **Handshake Verification Error**: TCP connection succeeded over IPv6, but the TLS certificate presented did not validate for hostname `{hostname}`.",
            "2. **Impact**: Modern browsers will block asset loading due to strict transport security (HSTS) or mixed-content policies.",
            "3. **Resolution**: Ensure the dual-stack server configuration binds the correct TLS certificate to the IPv6 socket.",
        ])
    else:
        lines.extend([
            f"1. **Verified IPv6 Operation**: Diagnostic probes confirmed end-to-end connectivity over IPv6 with valid responses.",
            "2. **Recommendation**: Continue monitoring during normal DNS TTL cycles.",
        ])

    lines.extend([
        "",
        "#### Recommended Next Steps:",
        f"- {finding.get('recommendation', 'Inspect host network and DNS configurations.')}",
        f"- Retest this endpoint individually using: `curl -6 -Iv https://{hostname}`",
    ])

    return "\n".join(lines)

async def explain_finding_with_ai(finding: Dict[str, Any]) -> Dict[str, Any]:
    """
    Evidence-grounded explanation. Uses Gemini API if configured, otherwise deterministic fallback.
    """
    # Check if API key is provided
    api_key = settings.GEMINI_API_KEY
    if not api_key:
        return {
            "source": "deterministic",
            "model": "NETSCOPE Deterministic Diagnostics Engine v1.0",
            "explanation": generate_deterministic_explanation(finding),
            "disclaimer": "Generated by deterministic diagnostic engine. Grounded strictly in test evidence.",
        }

    # If key is available, call Gemini safely
    prompt = f"""You are NETSCOPE INSIGHT, an IPv6 network engineer and systems diagnostician.
Analyze the following audit evidence for this finding.
STRICT RULES:
1. Distinguish observed facts, derived calculations, and plausible root causes.
2. Ground your response strictly in the provided evidence. NEVER invent DNS records or server configurations.
3. Keep the explanation concise, professional, and actionable.

FINDING DATA:
{json.dumps(finding, indent=2)}
"""

    try:
        async with httpx.AsyncClient(timeout=8.0) as client:
            resp = await client.post(
                f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key={api_key}",
                json={
                    "contents": [{"parts": [{"text": prompt}]}],
                    "generationConfig": {"temperature": 0.2, "maxOutputTokens": 600}
                }
            )
            if resp.status_code == 200:
                data = resp.json()
                text = data["candidates"][0]["content"]["parts"][0]["text"]
                return {
                    "source": "ai_assisted",
                    "model": "Gemini 2.0 Flash",
                    "explanation": text,
                    "disclaimer": "AI-assisted explanation grounded in diagnostic evidence. Always verify against system configurations.",
                }
    except Exception:
        pass

    # Fallback if AI call failed
    return {
        "source": "deterministic_fallback",
        "model": "NETSCOPE Deterministic Diagnostics Engine (Fallback)",
        "explanation": generate_deterministic_explanation(finding),
        "disclaimer": "Generated by deterministic engine following external API fallback.",
    }
